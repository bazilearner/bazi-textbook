#!/usr/bin/env node
/**
 * 教学式「推演底稿」生成器
 *
 * 解决的问题：脚本一个个跑，输出是五份独立的原料册；而报告要的是**按推导顺序排好的三十九张表（五步十柱各就各位）**。
 * 中间这一步没人做，模型就会「要点齐全、表格减半」——内容不错，但读者拿不到可复算的过程，
 * 于是报告从 26 页缩成 14 页，看起来「薄」。本脚本把这步做掉：
 *   · 按报告的章节顺序，把五份脚本输出摆到各自该在的位置；
 *   · 每节给出「本节必须有」的勾选清单（表数、最少行数、必须写「无」的项）；
 *   · 缺原料的节显式标 `[缺]`，不让它静默消失。
 *
 * 用法：
 *   node worksheet.js "1990-05-15 14:20" 1 116.41 2026 2036 > 底稿.md
 *   （性别 1=男 0=女；经度可省；年份区间可省，默认当年起 11 年）
 *
 * 产物是**底稿**，不是报告：文字仍须人写，但表一张都不会漏、数字一个都不用抄。
 */
const path = require('path');
const { execFileSync } = require('child_process');

const GAN = ['甲','乙','丙','丁','戊','己','庚','辛','壬','癸'];
const ZHI = ['子','丑','寅','卯','辰','巳','午','未','申','酉','戌','亥'];

function run(script, args) {
  try {
    return execFileSync(process.execPath, [path.join(__dirname, script), ...args],
      { encoding: 'utf8', env: process.env, stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 8 * 1024 * 1024 });
  } catch (e) {
    const out = (e.stdout || '') + (e.stderr || '');
    return `[缺] ${script} 执行失败：\n${out.slice(0, 600)}`;
  }
}

function py(script, args) {
  for (const bin of ['python3', 'python']) {
    try {
      return execFileSync(bin, [path.join(__dirname, script), ...args],
        { encoding: 'utf8', env: process.env, stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 8 * 1024 * 1024 });
    } catch (e) { /* 换下一个解释器 */ }
  }
  return '[缺] python 不可用——请手跑 truesolar.py（不影响其它节）';
}

function main() {
  const [dt, genderArg, lonArg, y1Arg, y2Arg] = process.argv.slice(2);
  if (!dt) {
    console.log('用法：node worksheet.js "YYYY-MM-DD HH:MM" [性别] [经度E] [起年] [止年]');
    process.exit(2);
  }
  const gender = genderArg === undefined ? 1 : Number(genderArg);
  const lon = lonArg === undefined ? 120.0 : Number(lonArg);
  const nowY = new Date().getFullYear();
  const y1 = y1Arg ? Number(y1Arg) : nowY;
  const y2 = y2Arg ? Number(y2Arg) : y1 + 10;

  /* 先排盘，后面所有脚本都以这四柱为输入 */
  const chartOut = run('paipan.js', ['chart', dt, String(gender)]);
  const m = chartOut.match(/四柱：\s*(\S+)\s+(\S+)\s+(\S+)\s+(\S+)/);
  if (!m) {
    console.log('[缺] 排盘失败，检查出生时刻格式与 NODE_PATH：\n' + chartOut.slice(0, 800));
    process.exit(1);
  }
  const gz = m.slice(1, 5).join(' ');
  const full = run('paipan.js', ['full', dt, String(gender), String(y1), String(y2)]);

  const O = [];
  const h = (t, lvl) => O.push(`\n${'#'.repeat(lvl)} ${t}\n`);
  const todo = (items) => O.push(items.map(x => `- [ ] ${x}`).join('\n') + '\n');
  const raw = (title, text) => {
    O.push(`\n**${title}（照抄，勿手算）**\n`);
    O.push('```\n' + String(text).trim() + '\n```\n');
  };

  O.push(`# 推演底稿 · 教学式（五步链）\n`);
  O.push(`> 命主：${gender === 1 ? '男' : '女'}　出生：${dt}　经度：${lon.toFixed(2)}°E`);
  O.push(`> 四柱：**${gz}**　流年区间：${y1}—${y2}`);
  O.push(`> 本底稿是**原料 + 勾选清单**，不是成稿。文字要自己写；表与数字一律照抄下面的块。`);
  O.push(`> 篇幅基线见 \`references/depth-baseline.md\`：教学式 **≥18 页 / ≥1.5 万字 / ≥30 张表**，达不到就是「薄」，不是「简洁」。\n`);

  /* ───────── 卷首 ───────── */
  h('卷首 · 一页纸（400—600 字，不出现术语）', 2);
  todo([
    '段① 身份物象（一句比喻：你是一株…／一块…）',
    '段② 主要矛盾（一句话，不用术语）',
    '段③ **先回答他问的那件事**（第 0 步问到的原话；没问清就声明假设）',
    '段④ 三条要点：靠什么 · 怕什么 · 什么时候顺（**给年龄 + 公历年份**）',
    '段⑤ 怎么读这份报告（给路径，不给术语表）',
    '自查：通读一遍，圈出所有术语——一个都不许有；有就换成白话或删',
  ]);

  /* ───────── 第 0 篇 怎么读 ───────── */
  h('第 0 篇 · 这份报告怎么读（**v1.7.0 起单列，不许省**）', 2);
  todo([
    '0.1 **五步链总览表**（步／名称／在干什么／输入／输出）——五行，照 `teaching-flow.md` §〇 抄',
    '0.2 **为什么是这个顺序**（四条理由，每条一段）——这是「教学式」与「结论式加长版」的分水岭',
    '0.3 **速览卡**（8 行：四柱／日主／旺衰／格局／喜忌／大运／起运／临界）——**每行一个结论，不解释**',
    '0.4 **术语对照**（只列本篇出现过的，10—15 行；右列必须落到本盘的字与位）',
  ]);
  raw('速览卡可用原料', run('wangshuai.js', ['summary', gz, dt]));

  /* ───────── 第一步 起盘 ───────── */
  h('第一步 · 起盘 ｜ A 四柱 · B 大运', 2);
  todo([
    '1.1 四柱推法表（柱／推法（依据）／本例推算过程／结果）——**四行，每行都要写规则**',
    '1.2 时辰边界：三口径表（口径／计算过程／所得时刻／归属时辰）＋ 距界秒数 ＋ 双盘对照表 ＋ 待验项',
    '1.3 十神配置表（位置／干支／干十神／支藏干十神）＋ 十神统计 ＋「十神不全」讨论',
    '1.4 大运：方向怎么定／起点／起运岁数算式 ＋ 大运表（九行左右）',
    '1.5 旬空（日柱属何旬 → 空哪两支 → 落点 → 取象）／胎元／命宫（只列口径）',
  ]);
  raw('排盘', chartOut);
  raw('真太阳时与边界（Python 版，与 boundary.js 互核）', py('truesolar.py', [dt.split(' ')[0], dt.split(' ')[1], String(lon), '出生地']));
  raw('边界双盘对照（node boundary.js）', run('boundary.js', [dt, String(gender), String(lon)]));
  raw('盘面明细（五行五栏／十神统计／生克逐对／逐类核含无／长生宫意／旬空／神煞查法）',
    run('detail.js', ['all', gz, dt, String(gender)]));

  /* ───────── 第二步 定旺衰 ───────── */
  h('第二步 · 定旺衰 ｜ A 四问 · B 计分', 2);
  todo([
    '2.1 月令与司令（节后第几日 → 当权之神 → 潜台词：得令为体、司令为用）',
    '2.2 ① 得令（旺相休囚死表 ＋ 日主所处 ＋ 判定）',
    '2.3 ② 得地（逐支四栏表 ＋ 本气/中气/余气 ＋ 禄刃墓）',
    '2.4 ③ 得生（印星落点四档）　2.5 ④ 得助（比劫落点三档 ＋ 比肩不充相神）',
    '2.6 ⑤ 克泄耗（官杀／食伤／财 各几处、在哪）',
    '2.7 ⑥ 力量计分（**13 行逐字表** ＋ 同类/异类合计 ＋ 占比 ＋ 判定线）',
    '2.8 ⑦ 四问汇总表 ＋ **两法互校**（背离时以「月令＋有无本气根」为准，写取舍理由）',
    '2.9 两条例外（旺极宜泄／弱极宜克）——**留口子推到第三步**，此处只给「常法之强弱」',
  ]);
  raw('定旺衰全套', run('wangshuai.js', ['all', gz, dt]));

  /* ───────── 第三步 取用神 ───────── */
  h('第三步 · 取用神 ｜ A 四门并参 · B 用神五档', 2);
  todo([
    '3.1 调候门：查表得常法 → 落点核验 → **修正与理由**（不许照抄表）',
    '3.2 理法门：**七维表**（气势／流通阻滞／衰旺／中和／寒暖燥湿／清浊／体用）＋ 核心判断 ＋ 治法一句',
    '3.3 病药门：**四病逐条判**（雕／枯／旺／弱，各注成病与否）＋ **四药逐条取**（损／益／生／长）',
    '3.4 格局门：此处只作引子，成败放第四步（纪律：取用求方向、辨格求成败）',
    '3.5 四门归一表（门／经典／所得／关键依据）',
    '3.6 五档表（用／相／喜／忌／闲）＋ **门类声明** ＋ **口径声明**',
    '3.7 落地表（方位／行业／颜色／环境／作息，各给宜·闲·忌）',
  ]);
  raw('调候查表与落点', run('tiaohou.js', ['check', gz]));

  /* ───────── 第四步 辨格局 ───────── */
  h('第四步 · 辨格局 ｜ A 成败救应 · B 相神定位', 2);
  todo([
    '4.1 月令透出对照表（藏干／十神／是否透干／透于何处／另通根）＋ 合冲判（合去的是忌神还是用神）',
    '4.2 取格 ＋ 依据条文（四生四正看司令／四库看透干会合／禄刃另走）',
    '4.3 顺逆用 ＋ **必写反直觉两篇**（四吉神能破格／四凶神能成格）',
    '4.4 相神候选表（**逐字 12 行**）＋ 判定理由三条 ＋ 副相（不作主）',
    '4.5 成败检查六条表（含「天干层」，**逐条含「无」**）＋ 四条口径判定',
    '4.6 生克逐对（只列有实义者）＋ 刑冲合害会逐类核表（十行，含「无」）＋ 盘性判定',
    '4.7 十二长生逐支表（支／长生／宫意）＋ 有无禄刃',
    '4.8 旬空　4.9 神煞表（**14 行：神煞／查法／落点／取象**）　4.10 格局高低四问',
  ]);
  raw('辨格局全套', run('geju.js', ['all', gz, dt]));

  /* ───────── 第五步 断岁运 ───────── */
  h('第五步 · 断岁运 ｜ A 引动链 · B 填实虚拱', 2);
  todo([
    '5.1 **引动链**表（关系／作用双方／被引动之字／该字十神／落宫／所主／层级）——**不少于 10 行**',
    '5.2 **填实虚拱表**（虚拱之字／由命局哪两柱拱／流年填实／是否成局／应期判断）——**不少于 4 行**；本步的 B 柱，不许并进逐年叙述里',
    '5.3 大运四层定性表（大运／①用相到位／②得根／③调候／④刑冲合害／性质）——**九行，四层四列不许并格**',
    '5.4 每运「可做／慎做／必做」三则（性质为吉才写「可做大事」；守运以守为主）',
    '5.5 **一生总运程分段落读**（童少年／青年／立业／壮年／中年末／晚年，六段，每段 3—5 句）',
    `5.6 逐年表（${y1}—${y2}：年／干支／运／引动／判断与动作）＋ 逐年小结点读`,
    '5.7 关键节点归纳（最佳窗口／次佳／需防守／主题切换／长期提示）',
    '5.8 **六亲应期**（一消一长同时成立：冲克某星之位是应的应期，同期另一星转旺则安好）',
  ]);
  raw('引动清单（大运一层）', run('suiyun.js', ['dayun', gz, dt, String(gender)]));
  raw(`逐年扫描 ${y1}—${y2}`, run('suiyun.js', ['scan', gz, dt, String(gender), String(y1), String(y2)]));
  raw('含流年的大运表（年段／年龄照抄，勿自行分桶）', full);

  /* ───────── 第六章 分项细读 ───────── */
  h('第六章 · 分项细读（每项标「由第几步推出」）', 2);
  todo([
    '6.1 十神六亲表（六亲／星或宫／本命情况／解读＋可靠度）——**六行，可靠度必标**',
    '6.2 富贵穷通（用神有力否／相神有情否／位置得所否／纯杂 → 总评「中格」类）',
    '6.3 性情表（来源／表现，5—6 行）＋ 合看小结',
    '6.4 疾病表（五行状态／传统对应／偏向提示）＋ 可执行观察项 ＋ **以现代医学为准**',
    '6.5 出身地位表（柱／宫位／星象／解读）',
    '6.6 落地动作表（场景／动作／依据）——**7 行，每行标依据**',
  ]);

  /* ───────── 第七章 回问 ───────── */
  h('第七章 · 回到你的问题（报告的落点）', 2);
  todo([
    '7.1 问题清单（**他的原话**，1—3 条，一条不漏）',
    '7.2 逐条回答（结论 → 依据见第几章第几步 → 成立条件）',
    '7.3 三个动作（今年可做／今年别做／三年内要准备，各标「见 X.X」）',
    '7.4 一句收束（知命不是认命，是知道劲往哪儿使）',
    '纪律：结论必须与卷首一致；推演推翻了卷首 → 回去改卷首，不许两处打架',
  ]);

  /* ───────── 附录 ───────── */
  h('附录 A—D', 2);
  todo([
    '附录 A 边界与口径（三口径表／距界秒数／双盘对照／待验项／两套计数口径／六档分层）',
    '附录 B 版本与分歧（人元分野版本、晚子时裁决、命宫口径、三刑名目——只列口径不作判据）',
    '附录 C **年度观察清单**（逐年一行：年／主题／建议动作——可直接撕下来贴墙上）',
    '附录 D 边界与免责（时辰／精度「十之六七」／流派／健康婚姻／用途）',
  ]);

  O.push('\n---\n');
  O.push('底稿完。下一步：');
  O.push('① 按 `references/depth-baseline.md` 的「五步十柱 + 三十九张表」逐项打勾，缺一张就回去补；');
  O.push('② 写成 Markdown，跑 `python3 scripts/render.py 报告.md -o 报告.pdf` 出稿（不必手写 reportlab）；');
  O.push('③ 跑 `python3 scripts/depthcheck.py 报告.pdf` 量厚度——**表是骨头，少了就是「薄」**。\n');

  console.log(O.join('\n'));
}

main();
